// Colors provides a several basic colors
#pragma once
#include <cstdint>

namespace Colors {
    inline constexpr uint16_t WHITE =      0xFFFF;
    inline constexpr uint16_t LIGHT_GRAY = 0xD6BA; inline constexpr uint16_t LIGHT_GREY = 0xD6BA;
    inline constexpr uint16_t GRAY =       0x94B2; inline constexpr uint16_t GREY =       0x94B2;
    inline constexpr uint16_t DARK_GRAY =  0x2945; inline constexpr uint16_t DARK_GREY =  0x2945;
    inline constexpr uint16_t BLACK =      0x0000;

    inline constexpr uint16_t RED =        0xF966;
    inline constexpr uint16_t ORANGE =     0xF426;
    inline constexpr uint16_t YELLOW =     0xEEA3;
    inline constexpr uint16_t GREEN =      0x96A5;
    inline constexpr uint16_t CYAN =       0x4655;
    inline constexpr uint16_t BLUE =       0x353E;
    inline constexpr uint16_t DEEP_BLUE =  0x8A9F;
    inline constexpr uint16_t PURPLE =     0xE15F;
    inline constexpr uint16_t MAGENTA =    0xFB36;
    inline constexpr uint16_t PINK =       0xF577;
}